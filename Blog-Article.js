/* ==========================================
   RENDER ARTICLE SECTIONS
========================================== */

function renderGallery(images = []) {
    if (!images.length) return "";

    return `
        <div class="article-image-gallery">
            ${images.map(item => `
                <figure>
                    <img
                        src="${item.src}"
                        alt="${item.alt}"
                        loading="lazy"
                    >
                    <figcaption>${item.caption}</figcaption>
                </figure>
            `).join("")}
        </div>
    `;
}

function renderSection(section, index) {
    const sectionId = `article-section-${index + 1}`;

    const paragraphs = (section.paragraphs || [])
        .map(paragraph => `<p>${paragraph}</p>`)
        .join("");

    const image = section.image ? `
        <img
            class="article-feature-image"
            src="${section.image}"
            alt="${section.alt || section.heading}"
            loading="lazy"
        >
    ` : "";

    const bullets = section.bullets?.length ? `
        <ul>
            ${section.bullets.map(item => `<li>${item}</li>`).join("")}
        </ul>
    ` : "";

    const tip = section.tip ? `
        <div class="article-tip">
            <h3>Grower Tip</h3>
            <p>${section.tip}</p>
        </div>
    ` : "";

    return `
        <section class="article-section" id="${sectionId}">
            <h2>${section.heading}</h2>
            ${paragraphs}
            ${image}
            ${renderGallery(section.gallery)}
            ${bullets}
            ${tip}
        </section>
    `;
}

/* ==========================================
   BUILD THE TABLE OF CONTENTS
========================================== */

function renderContents(article) {
    const contents = document.getElementById("articleContents");

    contents.innerHTML = article.sections.map((section, index) => `
        <li>
            <a href="#article-section-${index + 1}">
                ${section.heading.replace(/^\d+\.\s*/, "")}
            </a>
        </li>
    `).join("");
}

/* ==========================================
   RELATED ARTICLE CARDS
========================================== */

function renderRelatedArticles(currentKey) {
    const container = document.getElementById("relatedArticles");

    const related = Object.entries(articles)
        .filter(([key]) => key !== currentKey)
        .slice(0, 3);

    container.innerHTML = related.map(([key, article]) => `
        <article class="related-card">
            <a
                class="related-card-image"
                href="Blog-Article.html?article=${key}"
                aria-label="Read ${article.title}"
            >
                <img
                    src="${article.image}"
                    alt="${article.imageAlt}"
                    loading="lazy"
                >
            </a>

            <div class="related-card-body">
                <span class="related-category">${article.category}</span>

                <h3>
                    <a href="Blog-Article.html?article=${key}">
                        ${article.title}
                    </a>
                </h3>

                <p>${article.description}</p>

                <a
                    class="related-read-more"
                    href="Blog-Article.html?article=${key}"
                >
                    Read Article →
                </a>
            </div>
        </article>
    `).join("");
}

/* ==========================================
   LOAD THE SELECTED ARTICLE
========================================== */

function loadArticle() {
    const params = new URLSearchParams(window.location.search);
    const key = params.get("article") || "hydroponic";
    const article = articles[key];

    const content = document.getElementById("articleContent");

    document.getElementById("articleYear").textContent =
        new Date().getFullYear();

    if (!article) {
        document.title = "Article Not Found | HydroGrow";

        document.getElementById("articleHeroTitle").textContent =
            "Article Not Found";

        document.getElementById("articleHeroDescription").textContent =
            "This article may have moved. Explore our other growing guides.";

        content.innerHTML = `
            <div class="article-conclusion">
                <h2>We couldn't find that article.</h2>
                <p>Please return to our blog and select another post.</p>
                <a class="article-cta-btn" href="Blog.html">
                    Browse All Blogs →
                </a>
            </div>
        `;

        document.getElementById("articleContents").innerHTML = `
            <li><a href="Blog.html">Browse all articles</a></li>
        `;

        renderRelatedArticles("");
        return;
    }

    document.title = `${article.title} | HydroGrow`;

    document.getElementById("articleHeroTitle").textContent =
        article.title;

    document.getElementById("articleHeroDescription").textContent =
        article.description;

    document.getElementById("articleCategory").textContent =
        article.category;

    document.getElementById("articleReadTime").textContent =
        article.readTime;

    document.getElementById("breadcrumbTitle").textContent =
        article.title;

    document.getElementById("articleHero").style.backgroundImage =
        `url("${article.heroImage}")`;

    const sectionsHTML = article.sections
        .map((section, index) => renderSection(section, index))
        .join("");

    const tagsHTML = article.tags.map(tag =>
        `<span>${tag}</span>`
    ).join("");

    content.innerHTML = `
        <p class="article-intro">${article.intro}</p>

        <img
            class="article-feature-image"
            src="${article.image}"
            alt="${article.imageAlt}"
            fetchpriority="high"
        >

        <p class="article-image-caption">
            Explore the techniques and growing practices discussed in this guide.
        </p>

        ${sectionsHTML}

        <section class="article-conclusion">
            <h2>Final Thoughts</h2>
            <p>${article.conclusion}</p>

            <div class="article-tags">
                ${tagsHTML}
            </div>
        </section>
    `;

    renderContents(article);
    renderRelatedArticles(key);
}

/* ==========================================
   MOBILE NAVIGATION
========================================== */

function setupMobileNavigation() {
    const menuToggle = document.getElementById("menuToggle");
    const mainNav = document.getElementById("mainNav");

    menuToggle.addEventListener("click", () => {
        const isOpen = mainNav.classList.toggle("open");

        menuToggle.setAttribute("aria-expanded", String(isOpen));
        menuToggle.textContent = isOpen ? "✕" : "☰";
    });

    mainNav.querySelectorAll("a").forEach(link => {
        link.addEventListener("click", () => {
            mainNav.classList.remove("open");
            menuToggle.setAttribute("aria-expanded", "false");
            menuToggle.textContent = "☰";
        });
    });
}

/* ==========================================
   BACK TO TOP BUTTON
========================================== */

function setupBackToTop() {
    const button = document.getElementById("backToTop");

    window.addEventListener("scroll", () => {
        button.style.display = window.scrollY > 400 ? "flex" : "none";
    });

    button.addEventListener("click", () => {
        window.scrollTo({
            top: 0,
            behavior: "smooth"
        });
    });
}

/* ==========================================
   INITIALIZE WEBSITE
========================================== */

document.addEventListener("DOMContentLoaded", () => {
    loadArticle();
    setupMobileNavigation();
    setupBackToTop();
});
